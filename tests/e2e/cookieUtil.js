function normalizeBase64(input) {
    return input.replace(/[^A-Za-z0-9+/=]/g, "");
}

function base64ToUint8Array(base64Text) {
    const binaryString = atob(normalizeBase64(base64Text));
    const bytes = new Uint8Array(binaryString.length);

    for (let index = 0; index < binaryString.length; index += 1) {
        bytes[index] = binaryString.charCodeAt(index);
    }

    return bytes;
}

async function setPanDomainCookie() {
    const keyBytes = base64ToUint8Array(PRIVATE_KEY_BASE64);
    const cryptoKey = await crypto.subtle.importKey(
        "pkcs8",
        keyBytes.buffer,
        { name: "RSASSA-PKCS1-v1_5", hash: "SHA-256" },
        false,
        ["sign"],
    );

    const expires = Math.floor(Date.now() / 1000) + 60 * 60;
    const payload =
        `firstName=Playwright&` +
        `lastName=Tester&` +
        `email=composer.application@guardian.co.uk&` +
        `system=restorer-e2e&` +
        `authedIn=restorer-e2e&` +
        `expires=${expires}&` +
        `multifactor=true`;

    const dataB64 = btoa(payload);
    const signatureBuffer = await crypto.subtle.sign(
        "RSASSA-PKCS1-v1_5",
        cryptoKey,
        new TextEncoder().encode(payload),
    );

    const signatureB64 = btoa(
        String.fromCharCode(...new Uint8Array(signatureBuffer)),
    );
    const cookieValue = `${dataB64}.${signatureB64}`;

    document.cookie = `gutoolsAuth-assym=${cookieValue}; path=/`;
    return cookieValue;
}

